// Build:
//  1. app/      – the installable PWA: TypeScript → native ES modules in app/js, plus a generated service worker.
//  2. dist/ledger-preview.html – a single self-contained file you can double-click to preview (no server needed).
import { execSync } from 'node:child_process';
import { readdirSync, statSync, readFileSync, writeFileSync, rmSync, existsSync, mkdirSync } from 'node:fs';
import { join, relative } from 'node:path';
import { createHash } from 'node:crypto';

const root = new URL('..', import.meta.url).pathname;
const app = join(root, 'app');
const sha = (s, enc = 'hex') => createHash('sha256').update(s).digest(enc);

// ---- 1. PWA build ----
if (existsSync(join(app, 'js'))) rmSync(join(app, 'js'), { recursive: true });
execSync('tsc -p .', { cwd: root, stdio: 'inherit' });
writeFileSync(join(app, 'js', 'package.json'), '{"type":"module"}\n');

const files = [];
const walk = (d) => { for (const f of readdirSync(d)) { const p = join(d, f); if (statSync(p).isDirectory()) { if (f !== 'content') walk(p); } else if (!/sw\.js$|package\.json$/.test(f)) files.push(p); } };
walk(app); // content packs are excluded from precache; they are cached when first fetched and stored in IndexedDB on install
const hash = createHash('sha256'); files.sort().forEach((f) => hash.update(readFileSync(f)));
const version = hash.digest('hex').slice(0, 12);
const list = ['./', ...files.map((f) => './' + relative(app, f).split('\\').join('/'))];
writeFileSync(join(app, 'sw.js'), `// Generated by scripts/build.mjs. Cache-first app shell for offline use; no network calls beyond same-origin app files.
const VERSION = '${version}';
const CACHE = 'ledger-' + VERSION;
const ASSETS = ${JSON.stringify(list, null, 0)};
self.addEventListener('install', (e) => { e.waitUntil(caches.open(CACHE).then((c) => c.addAll(ASSETS)).then(() => self.skipWaiting())); });
self.addEventListener('activate', (e) => { e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('ledger-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener('fetch', (e) => {
  const url = new URL(e.request.url);
  if (e.request.method !== 'GET' || url.origin !== self.location.origin) return;
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then((hit) => hit || fetch(e.request).then((res) => {
    if (res.ok && res.type === 'basic') { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(e.request, copy)); }
    return res;
  }).catch(() => caches.match('./index.html'))));
});
`);
console.log(`Built app/: ${files.length} files; service worker cache version ${version}.`);

// ---- 2. Single-file preview ----
// TypeScript emits every module into one AMD bundle; a 15-line loader below runs it. No bundler dependency.
mkdirSync(join(root, 'build'), { recursive: true });
const tsMajor = Number(/Version (\d+)/.exec(execSync('tsc -v', { cwd: root }).toString())?.[1] ?? 5);
writeFileSync(join(root, 'build', 'tsconfig.preview.json'), JSON.stringify({
  extends: '../tsconfig.json', include: ['../src/**/*.ts'],
  compilerOptions: { module: 'AMD', moduleResolution: 'node10', outFile: './preview-bundle.js', outDir: null, ...(tsMajor >= 6 ? { ignoreDeprecations: '6.0' } : {}) },
}, null, 2));
execSync('tsc -p build/tsconfig.preview.json', { cwd: root, stdio: 'inherit' });
const bundle = readFileSync(join(root, 'build', 'preview-bundle.js'), 'utf8');
const loader = `(function () {
  'use strict';
  var defs = {}, mods = {};
  function define(name, deps, factory) { defs[name] = { deps: deps, factory: factory }; }
  function req(name) {
    if (mods[name]) return mods[name].exports;           // also returns partial exports for circular imports
    var d = defs[name]; if (!d) throw new Error('Preview build: module not found: ' + name);
    var m = mods[name] = { exports: {} };
    var r = d.factory.apply(null, d.deps.map(function (x) { return x === 'require' ? req : x === 'exports' ? m.exports : req(x); }));
    if (r !== undefined) m.exports = r;
    return m.exports;
  }
${bundle}
  req('app');
})();`;
const css = readFileSync(join(app, 'styles.css'), 'utf8');
const icon = `data:image/svg+xml;base64,${Buffer.from(readFileSync(join(app, 'icons', 'icon.svg'))).toString('base64')}`;
let html = readFileSync(join(app, 'index.html'), 'utf8');
const csp = `default-src 'none'; script-src 'sha256-${sha(loader, 'base64')}'; style-src 'sha256-${sha(css, 'base64')}'; img-src data: blob:; connect-src https://raw.githubusercontent.com https://api.open5e.com; font-src 'none'; object-src 'none'; base-uri 'none'; form-action 'none'`;
html = html
  .replace(/<meta http-equiv="Content-Security-Policy"[^>]*>/, `<meta http-equiv="Content-Security-Policy" content="${csp}">`)
  .replace(/\s*<link rel="manifest"[^>]*>/, '').replace(/\s*<link rel="apple-touch-icon"[^>]*>/, '')
  .replace(/<link rel="icon"[^>]*>/, `<link rel="icon" href="${icon}" type="image/svg+xml">`)
  .replace(/<link rel="stylesheet" href="styles.css">/, () => `<style>${css}</style>`)
  .replace(/<script type="module" src="js\/app.js"><\/script>/, '')
  .replace('</body>', () => `<script>${loader}</script>\n</body>`)
  .replace('<title>The Adventurer’s Ledger</title>', '<title>The Adventurer’s Ledger (preview)</title>');
if (!html.includes(loader) || !html.includes(css)) throw new Error('Preview build failed: could not inline assets.');
mkdirSync(join(root, 'dist'), { recursive: true });
writeFileSync(join(root, 'dist', 'ledger-preview.html'), html);
console.log(`Built dist/ledger-preview.html (${(html.length / 1024).toFixed(0)} KB). Double-click it to preview.`);
